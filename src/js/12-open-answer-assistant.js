const ASSIST_DROP = new Set('указ|привед|назва|запис|объяс|обосн|отмеч|прав|полн|вычис|найд|получ|сдела|выбр|приме|должн|содер|оформ|испол|соста|опреде|задан|описа|соотв|использ|примен|требу|нужн|верн|умей|умен|знат|сфор'.split('|'));

function assistFold(s) {
    return String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[^0-9a-zа-яәғқңөұүһі\s]/g, ' ').replace(/\s+/g, ' ').trim()
}

function assistSign(w) {
    return w.length >= 4 ? w.slice(0, 4) : ''
}

function assistTerms(text) {
    const out = [], seen = {};
    for (const w of assistFold(text).split(' ')) {
        if (!w) continue;
        if (/^\d+$/.test(w)) {
            if (w.length >= 3 && !seen[w]) { seen[w] = 1; out.push({ sign: w, word: w }) }
            continue
        }
        if (w.length < 4 || ASSIST_STOP.has(w)) continue;
        const s = assistSign(w);
        if (!s || seen[s] || ASSIST_DROP.has(s)) continue;
        seen[s] = 1;
        out.push({ sign: s, word: w })
    }
    return out
}

function spCollectNumbers(text) {
    const out = new Set(), re = /\d+(?:[.,]\d+)?/g;
    let m;
    while ((m = re.exec(String(text || '')))) {
        const raw = m[0].replace(',', '.'), v = Number(raw);
        if (!Number.isFinite(v)) continue;
        if (Math.abs(v) >= 10 || raw.includes('.')) out.add(Math.round(v * 1000) / 1000)
    }
    return out
}

function spSameNumber(a, b) {
    return Math.abs(a - b) <= .01 * Math.max(1, Math.abs(b))
}
